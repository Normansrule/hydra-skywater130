#!/usr/bin/env python3
"""
atlas_fpga.py -- the FPGA memory image, in action, from its own simulation.

    python3 tools/atlas_fpga.py        writes docs/atlas/fpga.json

No HYDRA image has run on a board, so this is not a capture. It replays
`make memboard` (fpga/tb_fpga_mem.sv: the RTL of the ecp5-evn-mem image driven
through its serial port by a testbench host) with a dump added, as
tools/atlas_traces.py does for other make targets, and keeps what a person at
the board would see happen: every byte on the serial line in both
directions, the bridge's command, every scratchpad write, every dispatch with
its engine and tag, how long each engine is busy, and every completion. The
run must print its PASS line through scripts/runsim.sh, or nothing is written.
Label: Recorded RTL Trace. The bench runs the serial port at 4 clocks per bit
instead of the image's baud rate, so the serial timing is compressed; the
order and the bytes are the image's own.

The place-and-route numbers shown beside it are read from docs/metrics.json
(Recorded Tool Output, nextpnr for that plan), never typed in.
"""
import json, pathlib, re, shutil, sys, tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import atlas_traces as A  # noqa: E402
import vcd                # noqa: E402

OUT = ROOT / "docs/atlas/fpga.json"
TB = "tb_fpga_mem"
D = f"{TB}.dut"
WANT = {
    "clk": f"{D}.clk", "rx": f"{D}.uart_rx_i", "tx": f"{D}.uart_tx_o",
    "rx_valid": f"{D}.u_bridge.u_rx.valid", "rx_data": f"{D}.u_bridge.u_rx.data",
    "tx_start": f"{D}.u_bridge.u_tx.start", "tx_data": f"{D}.u_bridge.u_tx.data",
    "cmd": f"{D}.u_bridge.cmd", "mem_we": f"{D}.mem_we", "mem_bank": f"{D}.mem_bank",
    "disp_valid": f"{D}.u_sys.disp_valid", "disp_accept": f"{D}.u_sys.disp_accept",
    "disp_engine": f"{D}.u_sys.disp_engine", "disp_tag": f"{D}.u_sys.disp_tag",
    "eng_busy": f"{D}.u_sys.eng_busy", "comp_valid": f"{D}.u_sys.comp_valid", "comp_tag": f"{D}.u_sys.comp_tag",
}
PLAN = "ecp5-evn-mem"


def main():
    tmp = tempfile.mkdtemp(prefix="atlas_fpga_")
    try:
        vcdf, log = A.make_run({"make": "memboard", "tb": TB, "window_ns": 10 ** 9}, tmp)
        sigs, ts, _ = vcd.read(vcdf, [re.escape(v) for v in WANT.values()])
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    passed = [l for l in log.splitlines() if l.startswith("PASS")]
    if not passed:
        raise SystemExit("atlas_fpga: make memboard printed no PASS line; refusing")
    missing = [k for k, v in WANT.items() if v not in sigs]
    if missing:
        raise SystemExit(f"atlas_fpga: signals missing from the dump: {missing}")
    edges = [t for t, v in sigs[WANT["clk"]]["changes"] if v == "1"]
    comp = A.compact(sigs, {k: v for k, v in WANT.items() if k != "clk"}, edges)
    s = A.S(comp)
    ev = []
    for c in s.rises("rx_valid"):
        ev.append({"c": c, "k": "in", "b": s.at("rx_data", c), "cmd": s.at("cmd", c)})
    for c in s.rises("tx_start"):
        ev.append({"c": c, "k": "out", "b": s.at("tx_data", c)})
    # scratchpad writes: one event per run of cycles with the write strobe high
    we = comp["mem_we"]["v"]
    for i, (c, v) in enumerate(we):
        if v == "1":
            end = we[i + 1][0] if i + 1 < len(we) else len(edges)
            ev.append({"c": c, "k": "bank", "bank": s.at("mem_bank", c), "n": end - c})
    for c in s.rises("disp_valid"):
        if s.at("disp_accept", c) or s.at("disp_accept", c + 1):
            ev.append({"c": c, "k": "disp", "eng": s.at("disp_engine", c), "tag": s.at("disp_tag", c)})
    for c in s.rises("comp_valid"):
        ev.append({"c": c, "k": "comp", "tag": s.at("comp_tag", c)})
    busy = [[c, int(v, 16) if v != "x" else 0] for c, v in comp["eng_busy"]["v"]]
    ev.sort(key=lambda e: (e["c"], e["k"]))
    # write runs, so a drawing can show a bank filling without 100 events
    m = json.loads((ROOT / "docs/metrics.json").read_text())
    pnr = next((b for b in m["boards"] if b["plan"] == PLAN), None)
    srcs = sorted(set(re.findall(r"(?<![\w/.-])((?:fpga|mem|sys|mom|common|engines)/[\w/.-]+\.(?:sv|v|py))", log)))
    out = {
        "_comment": "Generated by tools/atlas_fpga.py from make memboard. Simulation, not a board capture.",
        "label": "Recorded RTL Trace", "plan": PLAN, "test": f"make memboard ({TB})", "result": passed[-1][:160],
        "command": "make memboard", "repo_commit": A.git_head(ROOT), "tools": A.tool_versions(),
        "clock_ns": (edges[1] - edges[0]) * A.timescale_ns(ts), "cycles": len(edges),
        "serial_note": "the testbench runs the serial port at 4 clocks per bit, not at the image's baud rate",
        "engines": {"0": "CPU (latency model)", "1": "vector unit (latency model)", "2": "systolic array, fed from memory",
                    "3": "NTT (latency model)", "4": "crypto (latency model)"},
        "pnr": pnr, "pnr_source": "docs/metrics.json (nextpnr, Recorded Tool Output)",
        "sources": {f: A.sha(ROOT / f) for f in srcs if (ROOT / f).exists()},
        "busy": busy, "events": ev,
    }
    OUT.write_text(json.dumps(out, separators=(",", ":"), sort_keys=True) + "\n")
    k = {x: sum(1 for e in ev if e["k"] == x) for x in ("in", "out", "bank", "disp", "comp")}
    print(f"atlas_fpga: {passed[-1]}; {len(edges)} cycles; {k['in']} bytes in, {k['out']} out, {k['bank']} bank writes, "
          f"{k['disp']} dispatches, {k['comp']} completions; wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KiB)")


if __name__ == "__main__":
    main()
