"""
atlas_ttfit.py -- how the Tiny Tapeout tile sits on the chip, drawn to scale in millimetres.

Three views, every length read from a file, none typed:
  - the whole chip: Caravel's die and every pad of its padframe, from Caravel's public def/chip_io.def (the
    padframe Tiny Tapeout chips use), each pad sized by its macro in the PDK's sky130_ef_io.lef;
  - HYDRA's slot: the 4x4 tile size from Tiny Tapeout's tile_sizes.yaml and the hardened die from
    docs/tapeout/facts.json, with a 1x1 tile drawn in it for scale;
  - the pad pitch: three neighbouring GPIO pads from the same DEF, with their width and centre spacing.
Where the slot sits on a shuttle chip is assigned by Tiny Tapeout, so its place on the chip view is illustrative
and says so.

The DEF, LEF and tile_sizes.yaml are not in this repository (build/ext/ and the TT tooling are fetched), so the
lengths are kept in docs/tapeout/ttfit.json, with the source files and their sha256. The figure is drawn from that
file, on the site and as docs/img/ttfit.svg / ttfit.dark.svg for the README.

  python3 tools/atlas_ttfit.py            re-read the sources (when present) into ttfit.json, and draw the figure
  python3 tools/atlas_ttfit.py --check    the figure matches ttfit.json; ttfit.json matches the sources if present
"""
import hashlib
import html as H
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HOME = pathlib.Path.home()
OUT = ROOT / "docs/tapeout/ttfit.json"
DEF = ROOT / "build/ext/caravel/def/chip_io.def"
TILES = HOME / "src/tinytapeout-hydra/tt/tech/sky130A/tile_sizes.yaml"
FACTS = ROOT / "docs/tapeout/facts.json"
SLOT = "4x4"
esc = lambda s: H.escape(str(s), quote=True)


def rel(p):
    p = pathlib.Path(p)
    for base, name in ((ROOT, ""), (HOME, "~/")):
        try:
            return name + str(p.relative_to(base))
        except ValueError:
            pass
    return str(p)


def sha(p):
    return hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest()[:16]


def pdk_lef():
    """The PDK's I/O LEF, at the PDK the fact sheet names."""
    f = json.loads(FACTS.read_text())
    src = next(x["source_file"] for x in f["targets"]["tt_tile"]["facts"] if x["name"] == "process / PDK")
    root = pathlib.Path(src.replace("~/", str(HOME) + "/")).parent      # .../sky130A
    return root / "libs.ref/sky130_fd_io/lef/sky130_ef_io.lef"


def read_sources():
    """Everything the figure needs, from the DEF, the LEF, tile_sizes.yaml and the fact sheet."""
    lef = pdk_lef()
    for p in (DEF, lef, TILES):
        if not p.exists():
            return None, f"{rel(p)} not present"
    sizes = {m.group(1): (float(m.group(2)), float(m.group(3))) for m in
             re.finditer(r"MACRO (\S+)\n(?:(?!END ).*\n)*?\s*SIZE ([\d.]+) BY ([\d.]+)", lef.read_text())}
    t = DEF.read_text()
    dbu = int(re.search(r"UNITS DISTANCE MICRONS (\d+)", t).group(1))
    die = [int(v) / dbu for v in re.search(r"DIEAREA \( (\d+) (\d+) \) \( (\d+) (\d+) \)", t).groups()]
    pads = []
    for m in re.finditer(r"-\s+(\S+)\s+(sky130_ef_io__\S+)\s+\+\s+(?:PLACED|FIXED)\s+\(\s*(-?\d+)\s+(-?\d+)\s*\)\s+(\S+)", t):
        cell = m.group(2)
        if "slice" in cell or cell not in sizes:
            continue                                   # the bus slices between pads: not pads
        w, h = sizes[cell]
        if m.group(5) in ("E", "W", "FE", "FW"):
            w, h = h, w                                # a pad on a side edge is turned a quarter
        kind = "gpio" if "gpiov2" in cell else "corner" if "corner" in cell else "power"
        pads.append([kind, round(int(m.group(3)) / dbu, 3), round(int(m.group(4)) / dbu, 3), w, h])
    tiles = {m.group(1): [float(m.group(2)), float(m.group(3))] for m in
             re.finditer(r'^(\d+x\d+): "0 0 ([\d.]+) ([\d.]+)"', TILES.read_text(), re.M)}
    facts = json.loads(FACTS.read_text())["targets"]["tt_tile"]["facts"]
    die_f = next(x for x in facts if x["name"] == "die width x height")
    hydra = [float(v) for v in die_f["value"].split(" x ")]
    pitch = next((x for x in facts if x["name"].startswith("I/O pad pitch")), None)
    cell = sizes["sky130_ef_io__gpiov2_pad_wrapped"]
    return {
        "_comment": "Generated by tools/atlas_ttfit.py from the files named in sources; do not edit. Lengths in um.",
        "sources": {"padframe": {"file": rel(DEF), "sha256": sha(DEF), "note": "efabless/caravel def/chip_io.def"},
                    "pad_macros": {"file": rel(lef), "sha256": sha(lef)},
                    "tile_sizes": {"file": rel(TILES), "sha256": sha(TILES)},
                    "hydra_die": {"file": die_f["source_file"], "via": "docs/tapeout/facts.json"}},
        "chip_die": die[2:], "pads": sorted(pads, key=lambda p: (p[2], p[1])),
        "gpio_cell": list(cell), "pad_pitch": pitch["value"] if pitch and pitch.get("value") else None,
        "tiles": {"1x1": tiles["1x1"], SLOT: tiles[SLOT]}, "slot": SLOT, "hydra_die": hydra,
    }, None


# ---------------------------------------------------------------------------------------------------------- draw
def mm(um, d=3):
    return f"{um / 1000:.{d}f} mm"


def dim_h(x0, x1, y, label, cls="tf-d"):
    """A horizontal dimension line with end ticks and its label above."""
    return (f'<path class="{cls}" d="M{x0:.1f} {y:.1f}H{x1:.1f}M{x0:.1f} {y - 5:.1f}v10M{x1:.1f} {y - 5:.1f}v10"/>'
            f'<text class="tf-n" x="{(x0 + x1) / 2:.1f}" y="{y - 8:.1f}" text-anchor="middle">{esc(label)}</text>')


def dim_v(x, y0, y1, label, cls="tf-d", side=-1):
    tx = x + side * 8
    return (f'<path class="{cls}" d="M{x:.1f} {y0:.1f}V{y1:.1f}M{x - 5:.1f} {y0:.1f}h10M{x - 5:.1f} {y1:.1f}h10"/>'
            f'<text class="tf-n" x="{tx:.1f}" y="{(y0 + y1) / 2:.1f}" text-anchor="middle" '
            f'transform="rotate(-90 {tx:.1f} {(y0 + y1) / 2:.1f})">{esc(label)}</text>')


STYLE = ("<style>"
         ".tf-bg{fill:@bg}.tf-die{fill:@surface;stroke:@line;stroke-width:1.2}"
         ".tf-core{fill:@bg;stroke:@line2;stroke-width:1;stroke-dasharray:4 4}"
         ".tf-gpio{fill:@control;opacity:.85}.tf-pow{fill:@signal;opacity:.7}.tf-cor{fill:@dim;opacity:.6}"
         ".tf-slot{fill:@control;fill-opacity:.18;stroke:@control;stroke-width:1.6}"
         ".tf-tile{fill:@bg;fill-opacity:.55;stroke:@ink;stroke-width:1.5;stroke-dasharray:4 3}"
         ".tf-d{fill:none;stroke:@ink2;stroke-width:1}.tf-lead{fill:none;stroke:@control;stroke-width:1.2;stroke-dasharray:5 4}"
         ".tf-t{fill:@ink;font:600 15px 'Ubuntu Sans',ui-sans-serif,system-ui,sans-serif}"
         ".tf-n{fill:@ink;font:13px 'Ubuntu Sans Mono',ui-monospace,Menlo,Consolas,monospace}"
         ".tf-s{fill:@dim;font:12px 'Ubuntu Sans',ui-sans-serif,system-ui,sans-serif}"
         ".tf-pulse{animation:tfp 3.2s ease-in-out infinite}@keyframes tfp{0%,100%{fill-opacity:.12}50%{fill-opacity:.38}}"
         "@media (prefers-reduced-motion:reduce){.tf-pulse{animation:none}}"
         "</style>")


def svg(d, layout_href=None, standalone=True):
    W, Hh = 1200, 870
    cw, ch = d["chip_die"]
    # whole chip, left: fit 5.188 mm into 640 px
    s1 = 640 / ch
    X1, Y1 = 70, 70
    o = []
    o.append(f'<text class="tf-t" x="{X1}" y="40">The chip: Caravel padframe, {mm(cw)} × {mm(ch)}</text>')
    o.append(f'<rect class="tf-die" x="{X1}" y="{Y1}" width="{cw * s1:.1f}" height="{ch * s1:.1f}" rx="2"/>')
    cls = {"gpio": "tf-gpio", "power": "tf-pow", "corner": "tf-cor"}
    for k, x, y, w, h in d["pads"]:
        # DEF y grows up; the drawing's y grows down
        o.append(f'<rect class="{cls[k]}" x="{X1 + x * s1:.2f}" y="{Y1 + (ch - y - h) * s1:.2f}" '
                 f'width="{w * s1:.2f}" height="{h * s1:.2f}"/>')
    o.append(dim_h(X1, X1 + cw * s1, Y1 + ch * s1 + 26, mm(cw)))
    o.append(dim_v(X1 - 22, Y1, Y1 + ch * s1, mm(ch)))
    sw, sh = d["tiles"][d["slot"]]
    sx, sy = X1 + (cw / 2 - sw / 2) * s1, Y1 + (ch / 2 - sh / 2) * s1
    o.append(f'<rect class="tf-slot tf-pulse" x="{sx:.1f}" y="{sy:.1f}" width="{sw * s1:.1f}" height="{sh * s1:.1f}"/>')
    o.append(f'<text class="tf-s" x="{X1 + cw * s1 / 2:.1f}" y="{sy + sh * s1 + 18:.1f}" text-anchor="middle">'
             f'HYDRA, to scale; place illustrative</text>')

    # HYDRA's slot, right top: 682.64 um into 470 px
    X2, Y2 = 640, 70
    s2 = 470 / sw
    o.append(f'<text class="tf-t" x="{X2}" y="40">HYDRA\'s slot: Tiny Tapeout {d["slot"].replace("x", "×")} tiles</text>')
    if layout_href:
        o.append(f'<image href="{esc(layout_href)}" x="{X2}" y="{Y2}" width="{sw * s2:.1f}" height="{sh * s2:.1f}" '
                 f'preserveAspectRatio="none" opacity=".6"/>')
    o.append(f'<rect class="tf-slot" x="{X2}" y="{Y2}" width="{sw * s2:.1f}" height="{sh * s2:.1f}"/>')
    tw, th = d["tiles"]["1x1"]
    o.append(f'<rect class="tf-tile" x="{X2}" y="{Y2}" width="{tw * s2:.1f}" height="{th * s2:.1f}"/>')
    o.append(f'<text class="tf-s" x="{X2 + 6}" y="{Y2 + th * s2 + 16:.1f}">one 1×1 tile, {tw:.2f} × {th:.2f} µm</text>')
    o.append(dim_h(X2, X2 + sw * s2, Y2 + sh * s2 + 26, f"{mm(sw)} ({sw:.2f} µm)"))
    o.append(dim_v(X2 + sw * s2 + 22, Y2, Y2 + sh * s2, f"{mm(sh)} ({sh:.2f} µm)", side=1))
    hw, hh = d["hydra_die"]
    area = sw * sh / 1e6
    fits = "the hardened die fills the slot exactly" if [hw, hh] == [sw, sh] else f"hardened die {hw} × {hh} µm"
    o.append(f'<text class="tf-s" x="{X2}" y="{Y2 + sh * s2 + 52:.1f}">{area:.4f} mm²; {fits}</text>')
    # orthogonal leader from the slot on the chip to its enlargement
    ly = sy + sh * s1 / 2
    o.append(f'<path class="tf-lead" d="M{sx + sw * s1:.1f} {ly:.1f}H{X2 - 30}V{Y2 + sh * s2 / 2:.1f}H{X2}"/>')

    # pad pitch, right bottom: three neighbouring GPIO pads on the bottom edge
    pw, ph = d["gpio_cell"]
    trio = None
    gp = [p for p in d["pads"] if p[0] == "gpio"]
    for ax in (1, 2):                                  # an edge is a row of pads sharing y (bottom, top) or x (sides)
        other = 2 if ax == 1 else 1
        for v in sorted({p[other] for p in gp}):
            row = sorted((p[ax] for p in gp if p[other] == v))
            for i in range(len(row) - 2):
                if trio is None and d["pad_pitch"] and all(abs(row[i + j + 1] - row[i + j] - d["pad_pitch"]) < 1e-6 for j in range(2)):
                    trio = [r - row[i] for r in row[i:i + 3]]
    X3, Y3 = 640, 610
    o.append(f'<text class="tf-t" x="{X3}" y="{Y3 - 26}">The pad pitch, three neighbouring GPIO pads</text>')
    if trio:
        s3 = 470 / (trio[2] + pw)
        s3 = min(s3, 150 / ph)                         # keep the pads' true proportions and the panel's height
        for x in trio:
            o.append(f'<rect class="tf-gpio" x="{X3 + x * s3:.1f}" y="{Y3}" width="{pw * s3:.1f}" height="{ph * s3:.1f}" rx="2"/>')
        c0, c1 = X3 + pw / 2 * s3, X3 + (trio[1] + pw / 2) * s3
        yb = Y3 + ph * s3 + 24
        o.append(dim_h(c0, c1, yb, f"pitch {d['pad_pitch']:.0f} µm ({mm(d['pad_pitch'])})"))
        o.append(dim_h(X3 + trio[2] * s3, X3 + (trio[2] + pw) * s3, yb, f"{pw:.0f} µm"))
        o.append(f'<text class="tf-s" x="{X3}" y="{yb + 30:.1f}">sky130_ef_io__gpiov2_pad_wrapped, {pw:.3f} × {ph:.3f} µm</text>')
    # key
    ky = Y1 + ch * s1 + 70
    for i, (c, t) in enumerate((("tf-gpio", "GPIO pad"), ("tf-pow", "power pad"), ("tf-cor", "corner"),
                                ("tf-slot", "HYDRA 4×4 slot"))):
        o.append(f'<rect class="{c}" x="{X1 + i * 130}" y="{ky - 11}" width="14" height="14"/>'
                 f'<text class="tf-s" x="{X1 + i * 130 + 20}" y="{ky}">{t}</text>')
    o.append(f'<text class="tf-s" x="{X1}" y="{Hh - 16}">From {esc(d["sources"]["padframe"]["note"])} '
             f'(sha256 {d["sources"]["padframe"]["sha256"]}), the PDK\'s sky130_ef_io.lef, Tiny Tapeout\'s tile_sizes.yaml '
             f'and the hardened tile. Where the slot sits on a shuttle is assigned by Tiny Tapeout.</text>')
    head = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {Hh}"'
            + (f' width="{W}" height="{Hh}"' if standalone else ' class="ttfit"')
            + ' role="img" aria-labelledby="tf-cap"><title id="tf-cap">'
            + esc(f"To scale: the Caravel chip, {mm(cw)} by {mm(ch)}, with its {len(d['pads'])} pads; HYDRA's "
                  f"Tiny Tapeout {d['slot']} slot, {mm(sw)} by {mm(sh)}, drawn on it; the slot enlarged with a 1x1 "
                  f"tile of {tw} by {th} micrometres; and three GPIO pads {pw:.0f} micrometres wide at a "
                  f"{d['pad_pitch']} micrometre pitch.") + "</title>" + STYLE
            + f'<rect class="tf-bg" width="{W}" height="{Hh}" rx="16"/>')
    return head + "".join(o) + "</svg>"


def site_svg():
    """The figure for the page, in the page's own colour variables; '' when ttfit.json is missing."""
    if not OUT.exists():
        return ""
    s = svg(json.loads(OUT.read_text()), layout_href="media/layout.png", standalone=False)
    return re.sub(r"@([a-z0-9]+)", r"var(--\1)", s)


def main():
    sys.path.insert(0, str(ROOT / "tools"))
    import atlas_theme as T
    check = "--check" in sys.argv
    d, why = read_sources()
    bad = []
    if d is not None:
        text = json.dumps(d, indent=1) + "\n"
        if check:
            if not OUT.exists() or OUT.read_text() != text:
                bad.append(f"{rel(OUT)} differs from its sources")
        else:
            OUT.write_text(text)
    elif not OUT.exists():
        sys.exit(f"ttfit: {rel(OUT)} missing and {why}")
    data = json.loads(OUT.read_text())
    for name, text in T.variants("ttfit.svg", svg(data)):
        f = ROOT / "docs/img" / name
        if check:
            if not f.exists() or f.read_text() != text:
                bad.append(f"docs/img/{name} out of date")
        else:
            f.write_text(text)
    if bad:
        sys.exit("readme-ttfit: " + "; ".join(bad) + " -- run: python3 tools/atlas_ttfit.py")
    note = "" if d is not None else f" (sources not present: {why}; checked the figure against {rel(OUT)} only)"
    print(("readme-ttfit: the chip-fit figure matches docs/tapeout/ttfit.json" if check
           else "atlas_ttfit: wrote docs/tapeout/ttfit.json, docs/img/ttfit.svg and ttfit.dark.svg") + note)


if __name__ == "__main__":
    main()
