#!/usr/bin/env python3
"""
atlas_fonts.py -- the atlas's two typefaces, cut down to the characters the
page uses and kept in the repository, so the page needs no font download.

    ~/ttsetup/venv/bin/python tools/atlas_fonts.py      (needs fontTools)

Ubuntu Sans (variable: width 75-100, weight 100-800) for words, Ubuntu Sans
Mono (variable weight) for signal names, bytes and code. Both are the
Ubuntu Font Family, Ubuntu Font Licence 1.0, which permits embedding them in
a document; the licence is written beside them. Source: the fonts-ubuntu
package of the machine that runs this, recorded with its hashes in
docs/atlas/fonts/fonts.json. Output is WOFF (zlib), which every browser reads.
"""
import hashlib, json, pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs/atlas/fonts"
SRC = pathlib.Path("/usr/share/fonts/truetype/ubuntu")
FACES = {"sans": "UbuntuSans[wdth,wght].ttf", "mono": "UbuntuSansMono[wght].ttf"}
# Basic Latin, Latin-1, and the few symbols the page writes
TEXT = ("".join(chr(c) for c in range(0x20, 0x7F)) + "".join(chr(c) for c in range(0xA0, 0x100))
        + "–—‘’“”•…→←↑↓↔×÷−≤≥≈≠µ·₀₁₂³⁴ⁿ√∑πΔ✓✕")


def sha(p):
    return hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest()


def main():
    from fontTools import subset
    OUT.mkdir(parents=True, exist_ok=True)
    meta = {"_comment": "Generated by tools/atlas_fonts.py.", "faces": {}}
    for key, name in FACES.items():
        src = SRC / name
        dst = OUT / f"{key}.woff"
        opts = subset.Options()
        opts.flavor = "woff"
        opts.layout_features = ["kern", "liga", "tnum", "lnum", "case", "calt", "ccmp", "locl", "mark", "mkmk"]
        opts.name_IDs = ["*"]
        opts.notdef_outline = True
        f = subset.load_font(str(src), opts)
        s = subset.Subsetter(opts)
        s.populate(text=TEXT)
        s.subset(f)
        subset.save_font(f, str(dst), opts)
        meta["faces"][key] = {"source": str(src), "source_sha256": sha(src), "file": dst.name,
                              "sha256": sha(dst), "bytes": dst.stat().st_size}
        print(f"atlas_fonts: {name} -> {dst.relative_to(ROOT)} ({dst.stat().st_size // 1024} KiB)")
    pkg = subprocess.run(["dpkg-query", "-W", "-f", "${Version}", "fonts-ubuntu"], capture_output=True, text=True).stdout
    meta["package"] = f"fonts-ubuntu {pkg}".strip()
    cp = next(pathlib.Path("/usr/share/doc").glob("fonts-ubuntu*/copyright")).read_text()
    lic = cp[cp.index("License: Ubuntu-Font-Licence-1.0\n -----"):]
    lic = "\n".join(l[1:] if l.startswith(" ") else l for l in lic.split("\n")[1:])
    lic = re.sub(r"\n\.\n", "\n\n", lic).split("\nLicense:")[0]
    (OUT / "LICENCE-UFL-1.0.txt").write_text(
        "The files sans.woff and mono.woff in this folder are subsets of the Ubuntu Font Family,\n"
        "Copyright 2010-2022 Canonical Ltd, licensed under the Ubuntu Font Licence 1.0 below.\n\n" + lic.strip() + "\n")
    (OUT / "fonts.json").write_text(json.dumps(meta, indent=1, sort_keys=True) + "\n")


if __name__ == "__main__":
    main()
